import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const source = await readFile(new URL('../src/lib/smoothScroll.ts', import.meta.url), 'utf8');
const code = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
const { createScrollFollower } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
test('rapid lyric changes retarget one animation without jumps or competing frames', () => {
  let next = 0, position = 0;
  const frames = new Map();
  globalThis.requestAnimationFrame = fn => { frames.set(++next, fn); return next; };
  globalThis.cancelAnimationFrame = id => frames.delete(id);
  const tick = time => { const entries = [...frames]; frames.clear(); entries.forEach(([,fn]) => fn(time)); };
  const scroll = createScrollFollower(() => position, value => { position = value; });
  scroll.move(400, true); tick(16);
  const before = position;
  scroll.move(700, true); scroll.move(900, true);
  assert.equal(position, before);
  assert.equal(frames.size, 1);
  tick(32);
  assert.ok(position > before && position < 900);
  for (let i = 3; i < 100; i++) tick(i * 16);
  assert.equal(position, 900);
  assert.equal(frames.size, 0);
  scroll.move(1200, true); scroll.stop();
  assert.equal(frames.size, 0);
  scroll.move(200, false);
  assert.equal(position, 200);
  assert.equal(frames.size, 0);
});
